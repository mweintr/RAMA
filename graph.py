#!/usr/bin/env python3
"""Ghost Writer — book graph.

Cards (characters, places, concepts, events, ...) linked to each other and to the
exact line of the chapter they come from. Only chapters with `status: complete`
enter the graph; the trigger is the chapter `version` against the analyzed one.

  python3 graph.py check [--json]      what to analyze / re-analyze / suspended (read-only)
  python3 graph.py start               begin a sync: prints the work to do (diffs included)
  python3 graph.py diff N              changed paragraphs + source relocation for chapter N
  python3 graph.py commit N [N ...]    re-anchor sources, snapshot, rebuild, one-line report
  python3 graph.py build               validate cards, regenerate views / INDEX.md / graph.json
  python3 graph.py validate            validate only, write nothing
  python3 graph.py find TEXT | --chapter N    pertinent cards (lazy reading)
  python3 graph.py apply PATCH         add/remove entries in cards without hand-editing YAML
  python3 graph.py migrate OLD_DIR     convert a graph in the legacy Italian format

Layout (in the book root):
  graph/chapters.yaml          analyzed chapters: title, file, analyzed_version
  graph/snapshots/cNN.md       copy of the analyzed text (for diffs and validation)
  graph/cards/<type>/<id>.yaml the only files to edit
  graph/view/**, graph/INDEX.md, graph/graph.json   generated, never edit

Only the standard library + PyYAML.
"""
