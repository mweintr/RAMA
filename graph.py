def cmd_commit(book, args):
    r = status_report(book)
    for n in args.chapters:
        if n not in r["scan"]:
            sys.exit(f"chapter {n} not found in chapters/")
        if r["scan"][n]["status"] != "complete":
            sys.exit(f"chapter {n} is '{r['scan'][n]['status']}': only chapters with status: complete "
                     "enter the graph. Nothing changed.")
    book.cards_dir.mkdir(parents=True, exist_ok=True)
    book.snap_dir.mkdir(parents=True, exist_ok=True)
    backup = {p: p.read_bytes() for p in [book.chapters_file] + list(book.snap_dir.glob("*.md"))
              + list(book.cards_dir.rglob("*.yaml")) if p.exists()}
    cards = load_cards(book, [])
    plans = {n: chapter_diff(book, n, cards) for n in args.chapters}
    lost = [(n, x) for n, d in plans.items() for x in d["lost"]]
    if lost:
        print("Cannot commit: these sources lost their quote in the new text. Remove the fact if the text "
              "no longer says it, otherwise update source + quote:")
        for n, (card, item, ref) in lost:
            print(f"  {fmt_ref(*ref)}  {card['_path'].relative_to(book.root).as_posix()}  "
                  f"{q(item.get('text') or item.get('note') or '')}  quote: {q(item.get('quote'))}")
        return 1
    touched, moved = {}, 0
    for n, d in plans.items():
        orig = {}  # id(item) -> refs as parsed before any move (indexes stay stable)
        for card, item, ref, res, idx in d["moved"]:
            refs = orig.setdefault(id(item), parse_refs(item["source"]))
            refs[idx] = (n, res[0], res[1])
            item["source"] = ", ".join(fmt_ref(*x) for x in refs)
            touched[card["id"]] = card
            moved += 1
    for card in touched.values():
        write_card(card)
    graph = load_graph_chapters(book)
    for n in args.chapters:
        c = r["scan"][n]
        shutil.copyfile(book.root / c["file"], snapshot_path(book, n))
        graph[n] = {"title": c["title"], "file": c["file"], "analyzed_version": c["version"]}
    save_graph_chapters(book, graph)
    if not build(book, quiet=True):
        for p in list(book.snap_dir.glob("*.md")) + list(book.cards_dir.rglob("*.yaml")):
            if p not in backup:
                p.unlink()
        for p, data in backup.items():
            p.write_bytes(data)
        if book.chapters_file not in backup and book.chapters_file.exists():
            book.chapters_file.unlink()
        print("Commit undone: fix the errors above and run commit again.")
        return 1
    start = book.dir / ".sync-start.json"
    before = json.loads(start.read_text(encoding="utf-8")) if start.exists() else None
    after = card_hashes(book)
    errs = []
    cards = load_cards(book, errs)
    n_open = sum(len(c.get("open", []) or []) for c in cards.values())
    chs = ", ".join(f"c{n} v{r['scan'][n]['version']}" for n in args.chapters)
    if before is not None:
        prev = before.get("cards", {})
        new = [k for k in after if k not in prev]
        mod = [k for k in after if k in prev and prev[k] != after[k]]
        gone = [k for k in prev if k not in after]
        delta = n_open - before.get("open", 0)
        print(f"Graph synced ({chs}): {len(new)} new cards, {len(mod)} modified, {len(gone)} removed, "
              f"{moved} sources re-anchored · open questions: {delta:+d}, {n_open} total.")
        start.unlink()
    else:
        print(f"Graph synced ({chs}): {moved} sources re-anchored · {len(cards)} cards · open questions: {n_open} total.")
    return 0


