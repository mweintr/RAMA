def paragraphs(lines, rng):
    out, cur = [], None
    for k in range(rng[0], rng[1] + 1):
        t = lines[k - 1]
        if t.strip():
            if cur is None:
                cur = [k, k, [t]]
            else:
                cur[1] = k
                cur[2].append(t)
        elif cur is not None:
            out.append(cur)
            cur = None
    if cur is not None:
        out.append(cur)
    return [(a, b, " ".join(ts)) for a, b, ts in out]


def chapter_diff(book, n, cards=None):
    """Changed paragraphs and source relocation plan for chapter n."""
    rep = status_report(book)
    c = rep["scan"][n]
    new = (book.root / c["file"]).read_text(encoding="utf-8").split("\n")
    snap = snapshot_path(book, n)
    old = snap.read_text(encoding="utf-8").split("\n") if snap.exists() else []
    po, pn = paragraphs(old, body_range(old)) if old else [], paragraphs(new, body_range(new))
    sm = difflib.SequenceMatcher(None, [norm(p[2]) for p in po], [norm(p[2]) for p in pn], autojunk=False)
    changes = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != "equal":
            changes.append({"tag": tag, "removed": po[i1:i2], "added": pn[j1:j2]})
    mp, body = line_map(old, new), body_range(new)
    if cards is None:
        cards = load_cards(book, [])
    moved, lost, kept = [], [], 0
    for i, card in cards.items():
        for item in source_items(card):
            try:
                refs = parse_refs(item["source"])
            except ValueError:
                continue
            for idx, (ref, qt) in enumerate(zip(refs, quotes_of(item, len(refs)))):
                if ref[0] != n:
                    continue
                res = relocate(ref, qt, old, new, mp, body) if qt else None
                if res is None:
                    lost.append((card, item, ref))
                elif res != (ref[1], ref[2]):
                    moved.append((card, item, ref, res, idx))
                else:
                    kept += 1
    return {"changes": changes, "moved": moved, "lost": lost, "kept": kept, "full": not old}


def print_diff(book, n, d):
    rel = lambda card: card["_path"].relative_to(book.root).as_posix()
    print(f"\n── Chapter {n}: changed paragraphs ({len(d['changes'])}) ──")
    if d["full"]:
        print("  no snapshot: read the whole chapter")
    for ch in d["changes"]:
        for a, b, t in ch["removed"]:
            print(f"  - old {fmt_ref(n, a, b)}: {t}")
        for a, b, t in ch["added"]:
            print(f"  + new {fmt_ref(n, a, b)}: {t}")
    print(f"── Chapter {n}: sources — {d['kept']} unchanged, {len(d['moved'])} moved "
          f"(re-anchored by commit), {len(d['lost'])} lost ──")
    for card, item, ref, res, _ in d["moved"]:
        print(f"  moved {fmt_ref(*ref)} → {fmt_ref(n, *res)}  {rel(card)}")
    for card, item, ref in d["lost"]:
        print(f"  LOST  {fmt_ref(*ref)}  {rel(card)}  text: {q(item.get('text') or item.get('note') or '')}"
              f"  quote: {q(item.get('quote'))}")


