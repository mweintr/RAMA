class Book:
    def __init__(self, root):
        self.root = Path(root)
        cfg = self.root / "book.config.json"
        self.config = json.loads(cfg.read_text(encoding="utf-8")) if cfg.exists() else {}
        self.lang = self.config.get("language", "en")
        self.L = LABELS.get(self.lang, LABELS["en"])
        self.preset = self.config.get("preset", "fiction")
        self.types = self._types()
        self.plural = {sing: folder for folder, sing in self.types}
        self.dir = self.root / "graph"
        self.cards_dir, self.view_dir = self.dir / "cards", self.dir / "view"
        self.snap_dir = self.dir / "snapshots"
        self.chapters_file = self.dir / "chapters.yaml"

    def _types(self):
        for base in (self.root, SCRIPT_DIR):
            p = base / "presets" / f"{self.preset}.md"
            if p.exists():
                m = re.search(r"```graph-types\n(.*?)```", p.read_text(encoding="utf-8"), re.S)
                if m:
                    out = []
                    for line in m.group(1).splitlines():
                        mm = re.match(r"\s*([a-z][a-z-]*)\s*:\s*([a-z][a-z-]*)", line)
                        if mm:
                            out.append((mm.group(1), mm.group(2)))
                    if out:
                        return out
        return FICTION_TYPES if self.preset in NARRATIVE_PRESETS else ESSAY_TYPES

    def type_label(self, folder):
        return TYPE_LABELS.get(self.lang, {}).get(folder, folder.capitalize())

    @property
    def has_events(self):
        return "event" in self.plural


# ─── Chapters ─────────────────────────────────────────────────────────────────

def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    try:
        return yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        return {}


def body_range(lines):
    """1-based [start, end] of the chapter text: after the frontmatter, before the Demolition Log."""
    start = 1
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                start = i + 2
                break
    end = len(lines)
    for i in range(start - 1, len(lines)):
        if re.match(r"#{1,3}\s+Demolition Log\b", lines[i]):
            end = i
            while end >= start and (not lines[end - 1].strip() or lines[end - 1].strip() == "---"):
                end -= 1
            break
    return start, end


def scan_chapters(book):
    """{num: {file, title, status, version}} for every chapters/**/NN-*.md."""
    out = {}
    for f in sorted((book.root / "chapters").rglob("*.md")):
        m = re.match(r"(\d+)", f.name)
        if not m:
            continue
        text = f.read_text(encoding="utf-8")
        fm = frontmatter(text)
        fmm = re.match(r"---\n(.*?)\n---\n", text, re.S)
        vm = re.search(r"^version:[ \t]*['\"]?([^'\"\n]*?)['\"]?[ \t]*$", fmm.group(1), re.M) if fmm else None
        out[int(m.group(1))] = {
            "file": f.relative_to(book.root).as_posix(), "title": str(fm.get("title", f.stem)),
            "status": str(fm.get("status", "")).strip(), "version": vm.group(1) if vm else str(fm.get("version", "?"))}
    return out


def load_graph_chapters(book):
    if not book.chapters_file.exists():
        return {}
    data = yaml.safe_load(book.chapters_file.read_text(encoding="utf-8")) or {}
    return {int(k): v for k, v in data.items()}


def save_graph_chapters(book, chs):
    lines = []
    for n in sorted(chs):
        c = chs[n]
        parts = [f"title: {q(c['title'])}", f"file: {c['file']}",
                 f"analyzed_version: {q(str(c['analyzed_version']))}"]
        for k in ("partial", "full_reread"):
            if c.get(k):
                parts.append(f"{k}: true")
        lines.append(f"{n}: {{{', '.join(parts)}}}")
    book.chapters_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def snapshot_path(book, n):
    return book.snap_dir / f"c{n:02d}.md"


def status_report(book):
    scan, graph = scan_chapters(book), load_graph_chapters(book)
    new, changed, suspended, current, drafts, missing, silent = [], [], [], [], [], [], []
    for n, c in sorted(scan.items()):
        g = graph.get(n)
        if c["status"] != "complete":
            if g:
                suspended.append(n)
            else:
                drafts.append(n)
            continue
        if not g:
            new.append(n)
        elif c["version"] != str(g["analyzed_version"]) or g.get("full_reread"):
            changed.append(n)
        else:
            current.append(n)
            snap = snapshot_path(book, n)
            if snap.exists() and snap.read_text(encoding="utf-8") != (book.root / c["file"]).read_text(encoding="utf-8"):
                silent.append(n)
    missing = [n for n in graph if n not in scan]
    return {"exists": book.dir.exists(), "new": new, "changed": changed, "suspended": suspended,
            "current": current, "drafts": drafts, "missing": missing, "silent": silent,
            "scan": scan, "graph": graph}


# ─── Text matching ────────────────────────────────────────────────────────────

_TRANS = str.maketrans({"’": "'", "‘": "'", "`": "'", "«": '"', "»": '"', "“": '"', "”": '"',
                        "„": '"', "‹": "'", "›": "'", "–": "-", "—": "-", "…": "...", "*": "", "_": "",
                        " ": " "})


def norm(s):
    return re.sub(r"\s+", " ", str(s).translate(_TRANS)).strip().casefold()


REF_RE = re.compile(r"c(\d+):(\d+)(?:-(\d+))?$")


def parse_refs(src):
    """'c3:19, c4:2-5' -> [(3, 19, 19), (4, 2, 5)]; raises ValueError."""
    out = []
    for piece in re.split(r"[,;]\s*", str(src).strip()):
        m = REF_RE.fullmatch(piece.strip())
        if not m:
            raise ValueError(piece)
        a = int(m.group(2))
        out.append((int(m.group(1)), a, int(m.group(3) or a)))
    return out


def fmt_ref(ch, a, b):
    return f"c{ch}:{a}" + (f"-{b}" if b != a else "")


def quotes_of(item, n):
    qv = item.get("quote")
    if qv is None:
        return [None] * n
    if isinstance(qv, list):
        return (qv + [None] * n)[:n]
    return [qv] + [None] * (n - 1) if n > 1 else [qv]


def quote_in(lines, a, b, quote):
    if not quote:
        return False
    return norm(quote) in norm(" ".join(lines[a - 1:b]))


def source_items(obj):
    """Every dict carrying a 'source' inside a card (traits, facts, relations, ...)."""
    if isinstance(obj, dict):
        if "source" in obj:
            yield obj
        for k, v in obj.items():
            if k != "source":
                yield from source_items(v)
    elif isinstance(obj, list):
        for x in obj:
            yield from source_items(x)


def line_map(old, new):
    """old line number (1-based) -> approximate new line number."""
    sm = difflib.SequenceMatcher(None, old, new, autojunk=False)
    mp = {}
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        for k in range(i1, i2):
            mp[k + 1] = (j1 + min(k - i1, max(j2 - j1 - 1, 0)) + 1) if j2 > j1 else j1 + 1
    return mp


def relocate(ref, quote, old_lines, new_lines, mp, body):
    """Return the new (a, b) for a source, or None if the quote is gone."""
    ch, a, b = ref
    if quote_in(new_lines, a, b, quote) and body[0] <= a and b <= body[1]:
        return a, b
    qn = norm(quote)
    width = b - a
    # line of the quote inside the old range (to keep the range shape)
    q_old = next((k for k in range(a, b + 1) if k <= len(old_lines) and qn in norm(old_lines[k - 1])), a)
    target = mp.get(q_old, q_old)
    hits = [k for k in range(body[0], body[1] + 1) if qn in norm(new_lines[k - 1])]
    if not hits and width:  # quote spanning lines: windows of the same width
        hits = [k for k in range(body[0], body[1] - width + 1)
                if qn in norm(" ".join(new_lines[k - 1:k + width]))]
        if hits:
            s = min(hits, key=lambda k: abs(k - mp.get(a, a)))
            return s, s + width
    if not hits:
        return None
    s = min(hits, key=lambda k: abs(k - target))
    na, nb = a + (s - q_old), b + (s - q_old)
    na, nb = max(na, body[0]), min(nb, body[1])
    if not quote_in(new_lines, na, nb, quote):
        na, nb = s, s
    return na, nb


# ─── Cards I/O (canonical, one entry per line) ────────────────────────────────

KEY_ORDER = ["id", "name", "aliases", "chapters", "chapter", "order", "when", "where", "on_stage",
             "involved", "after", "summary", "traits", "facts", "state", "not_said", "open", "relations"]
ITEM_ORDER = ["chapter", "to", "type", "text", "note", "source", "quote"]
_PLAIN = re.compile(r"[a-z][a-z0-9-]*$")
_RESERVED = {"true", "false", "yes", "no", "on", "off", "null", "y", "n"}


def q(s):
    return json.dumps(s, ensure_ascii=False)


def scalar(v, plain_ok=False):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if v is None:
        return "null"
    s = str(v)
    if plain_ok and _PLAIN.match(s) and s not in _RESERVED:
        return s
    return q(s)


def flow(v, plain_ok=False):
    if isinstance(v, list):
        return "[" + ", ".join(flow(x, plain_ok) for x in v) + "]"
    if isinstance(v, dict):
        keys = [k for k in ITEM_ORDER if k in v] + [k for k in v if k not in ITEM_ORDER]
        return "{" + ", ".join(f"{k}: {flow(v[k])}" for k in keys) + "}"
    return scalar(v, plain_ok)


def dump_card(d):
    keys = [k for k in KEY_ORDER if k in d] + [k for k in d if k not in KEY_ORDER and k != "_type"]
    out = []
    for k in keys:
        v = d[k]
        if isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
            out.append(f"{k}:")
            out += [f"  - {flow(x)}" for x in v]
        elif isinstance(v, list):
            out.append(f"{k}: {flow(v, plain_ok=True)}")
        else:
            out.append(f"{k}: {scalar(v, plain_ok=k in ('id', 'where'))}")
    return "\n".join(out) + "\n"


def load_cards(book, errors):
    cards = {}
    known = {folder for folder, _ in book.types}
    if not book.cards_dir.exists():
        return cards
    for d in sorted(p for p in book.cards_dir.iterdir() if p.is_dir()):
        if d.name not in known:
            errors.append(f"cards/{d.name}/: not a card type of preset '{book.preset}' "
                          f"({', '.join(sorted(known))})")
            continue
    for folder, sing in book.types:
        for f in sorted((book.cards_dir / folder).glob("*.yaml")):
            try:
                data = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
            except yaml.YAMLError as e:
                errors.append(f"{f.relative_to(book.dir)}: invalid YAML ({e})")
                continue
            data = {k: v for k, v in data.items() if v is not None}
            if data.get("id") != f.stem:
                errors.append(f"{f.relative_to(book.dir)}: id '{data.get('id')}' differs from file name")
                data["id"] = f.stem
            if data["id"] in cards:
                errors.append(f"duplicate id: {data['id']}")
            data["_type"], data["_path"] = sing, f
            cards[data["id"]] = data
    return cards


def write_card(d):
    path = d["_path"]
    clean = {k: v for k, v in d.items() if not k.startswith("_")}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_card(clean), encoding="utf-8")


def card_hashes(book):
    if not book.cards_dir.exists():
        return {}
    return {p.relative_to(book.cards_dir).as_posix(): hashlib.sha1(p.read_bytes()).hexdigest()
            for p in book.cards_dir.rglob("*.yaml")}


def open_count(book):
    return sum(len(c.get("open", []) or []) for c in load_cards(book, []).values())


# ─── Validation ───────────────────────────────────────────────────────────────

def chapter_texts(book, graph_chs):
    """Analyzed text of each graph chapter (from the snapshot)."""
    texts = {}
    for n in graph_chs:
        p = snapshot_path(book, n)
        if p.exists():
            texts[n] = p.read_text(encoding="utf-8").split("\n")
    return texts


def edges_of(cards):
    edges = []
    for i, n in cards.items():
        for r in n.get("relations", []) or []:
            edges.append({"from": i, "to": r.get("to"), "type": r.get("type", ""),
                          "note": r.get("note", ""), "source": r.get("source", "")})
        if n["_type"] == "event":
            for x in n.get("involved", []) or []:
                edges.append({"from": i, "to": x, "type": "involves", "note": "", "source": ""})
            if n.get("where"):
                edges.append({"from": i, "to": n["where"], "type": "happens in", "note": "", "source": ""})
            for x in n.get("after", []) or []:
                edges.append({"from": x, "to": i, "type": "leads to", "note": "", "source": ""})
    return edges


def validate(book, cards, graph_chs, errors, warnings):
    texts = chapter_texts(book, graph_chs)
    for n in graph_chs:
        if n not in texts:
            errors.append(f"chapter {n}: snapshot {snapshot_path(book, n).relative_to(book.root)} missing")
    for i, card in cards.items():
        where = card["_path"].relative_to(book.dir).as_posix()
        if "name" not in card:
            errors.append(f"{where}: missing 'name'")
        if card["_type"] == "event":
            for k in ("chapter", "order"):
                if k not in card:
                    errors.append(f"{where}: event without '{k}'")
            if card.get("chapter") is not None and card["chapter"] not in graph_chs:
                errors.append(f"{where}: event in chapter {card['chapter']}, which is not analyzed")
        for item in source_items(card):
            try:
                refs = parse_refs(item["source"])
            except ValueError as e:
                errors.append(f"{where}: source '{e}' is not in the form cN:line or cN:a-b")
                continue
            quotes = quotes_of(item, len(refs))
            for (ch, a, b), qt in zip(refs, quotes):
                r = fmt_ref(ch, a, b)
                if ch not in graph_chs:
                    errors.append(f"{where}: source {r} cites chapter {ch}, which is not analyzed "
                                  f"(only chapters with status: complete enter the graph)")
                    continue
                lines = texts.get(ch)
                if lines is None:
                    continue
                s, e = body_range(lines)
                if a < s or b > e or a > b:
                    errors.append(f"{where}: source {r} outside the chapter text (lines {s}-{e})")
                elif not qt:
                    errors.append(f"{where}: source {r} without a quote")
                elif not quote_in(lines, a, b, qt):
                    errors.append(f"{where}: source {r}, quote not found there: {q(qt)}")
                elif len(str(qt).split()) > 30:
                    warnings.append(f"{where}: source {r}, quote longer than 30 words")
    for e in edges_of(cards):
        for k in ("from", "to"):
            if e[k] not in cards:
                errors.append(f"edge {e['from']} → {e['to']} ({e['type']}): '{e[k]}' does not exist")


# ─── Views ────────────────────────────────────────────────────────────────────

def build(book, quiet=False):
    errors, warnings = [], []
    graph_chs = load_graph_chapters(book)
    cards = load_cards(book, errors)
    validate(book, cards, graph_chs, errors, warnings)
    if errors:
        print("ERRORS:\n  " + "\n  ".join(errors))
        return False
    L, P = book.L, book.plural
    edges = edges_of(cards)
    events = sorted((n for n in cards.values() if n["_type"] == "event"), key=lambda e: e["order"])
    struct = {"involves", "happens in", "leads to"}
    rep = status_report(book)

    def link(i):
        if i not in cards:
            return f"**{i}?**"
        n = cards[i]
        return f"[{n['name']}](../{P[n['_type']]}/{i}.md)"

    def fs(src):
        if not src:
            return ""
        return "*(" + re.sub(r"c(\d+):", lambda m: f"{L['ch']} {m.group(1)} {L['l']} ", str(src)) + ")*"

    def chaps(n):
        s = set(n.get("chapters", []) or [])
        if n.get("chapter") is not None:
            s.add(n["chapter"])
        for it in source_items(n):
            try:
                s.update(r[0] for r in parse_refs(it["source"]))
            except ValueError:
                pass
        return sorted(s)

    if book.view_dir.exists():
        shutil.rmtree(book.view_dir)
    for folder, _ in book.types:
        (book.view_dir / folder).mkdir(parents=True)
    (book.view_dir / "chapters").mkdir(parents=True)

    for i, n in cards.items():
        cs = chaps(n)
        o = [f"# {n['name']}", "", f"`{i}` · {book.type_label(P[n['_type']])}" + (f" · {L['chapters']}: {', '.join(map(str, cs))}" if cs else "")]
        if n.get("aliases"):
            o.append(f"\n{L['aliases']}: {', '.join(map(str, n['aliases']))}")
        o += ["", str(n.get("summary", "")).strip(), ""]
        if n["_type"] == "event":
            o += [f"- **{L['chapter']}**: [{n['chapter']}](../chapters/{n['chapter']:02d}.md)",
                  f"- **{L['when']}**: {n.get('when', '—')}",
                  f"- **{L['on_stage']}**: {L['yes'] if n.get('on_stage', True) else L['offstage']}"]
            if n.get("where"):
                o.append(f"- **{L['where']}**: {link(n['where'])}")
            o.append(f"- **{L['involved']}**: " + ", ".join(link(x) for x in n.get("involved", []) or []))
            before = [link(x) for x in n.get("after", []) or []]
            then = [link(e["id"]) for e in events if i in (e.get("after") or [])]
            o += [f"- **{L['comes_from']}**: " + (", ".join(before) or "—"),
                  f"- **{L['leads_to']}**: " + (", ".join(then) or "—"), ""]
        for key in ("traits", "facts", "not_said", "open"):
            if n.get(key):
                o += [f"## {L[key]}", ""]
                for x in n[key]:
                    o.append(f"- {x.get('text', '')} {fs(x.get('source'))}".rstrip())
                o.append("")
        if n.get("state"):
            o += [f"## {L['state']}", ""]
            for x in n["state"]:
                o.append(f"- **{L['ch'].capitalize()} {x.get('chapter')}** — {x.get('text', '')} {fs(x.get('source'))}".rstrip())
            o.append("")
        out_e = [e for e in edges if e["from"] == i and e["type"] not in struct]
