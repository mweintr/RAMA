    if r["silent"]:
        print("NOTE: text changed without a version bump (ignored until the version changes): " +
              ", ".join(f"c{n}" for n in r["silent"]))
    if not todo:
        print(f"Graph up to date: {len(r['current'])} chapters aligned"
              + (f", {len(r['suspended'])} suspended" if r["suspended"] else "")
              + (f", {len(r['drafts'])} drafts ignored" if r["drafts"] else "") + ".")
    return 0


