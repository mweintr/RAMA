def cmd_apply(book, args):
    """Patch format (one entry per line, values in YAML flow syntax):
         @ characters/tom                      (card; created if missing, name: required)
         traits: {text: "...", source: "c4:9", quote: "..."}     append to a list
         aliases+: "new alias"                 append to a list of strings
         -traits: "text prefix"                remove the entries whose text starts with it
         summary: "new summary"                set a scalar
    """
    card, folder = None, None
    errs = []
    cards = load_cards(book, errs)
    changed = {}
    for raw in Path(args.patch).read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith("@ "):
            ref = raw[2:].split()[0]
            folder, _, cid = ref.rpartition("/")
            if cid in cards:
                card = cards[cid]
            else:
                if folder not in book.plural.values():
                    sys.exit(f"unknown card type '{folder}' for new card {cid}")
                card = {"id": cid, "_type": dict(book.types)[folder], "_path": book.cards_dir / folder / f"{cid}.yaml"}
                cards[cid] = card
            changed[card["id"]] = card
            continue
        if card is None:
            sys.exit(f"entry before any '@ card' line: {raw}")
        key, _, val = raw.partition(": ")
        v = yaml.safe_load(val)
        if key.startswith("-"):
            key = key[1:]
            card[key] = [x for x in card.get(key, []) or []
                         if not (isinstance(x, dict) and any(norm(x.get(f) or "").startswith(norm(v)) and (v or not x.get("text"))
                                                             for f in ("text", "to", "note"))
                                 or not isinstance(x, dict) and norm(x).startswith(norm(v)))]
        elif key.endswith("+") or isinstance(v, dict):
            key = key.rstrip("+")
            lst = card.setdefault(key, []) or []
            if v not in lst:
                lst.append(v)
            card[key] = lst
        else:
            card[key] = v
    for c in changed.values():
        if "name" not in c:
            sys.exit(f"card {c['id']}: missing name")
        write_card(c)
    print(f"{len(changed)} cards written: " + ", ".join(sorted(changed)))
    return 0


