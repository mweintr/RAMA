_QUOTED = re.compile(r"«([^»]+)»|“([^”]+)”|\"([^\"]+)\"")
_STOP = set("il lo la i gli le un uno una di a da in con su per tra fra e o che non si ne ci del della dei "
            "delle al alla ai alle nel nella sul sulla è the a an of to in on and or is it that for with as at".split())


def rename_keys(obj, unknown):
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            nk = LEGACY_KEYS.get(k, k)
            if nk == k and k not in KEY_ORDER and k not in ITEM_ORDER and k != "id":
                unknown.add(k)
            out[nk] = rename_keys(v, unknown)
        return out
    if isinstance(obj, list):
        return [rename_keys(x, unknown) for x in obj]
    return obj


def _excerpt(line, toks, a, b, min_words=6, max_words=14):
    """Exact slice of `line` covering tokens a..b-1, widened to at least min_words."""
    b = min(b, a + max_words)
    while b - a < min_words and (a > 0 or b < len(toks)):
        if b < len(toks):
            b += 1
        if b - a < min_words and a > 0:
            a -= 1
    return line[toks[a][1]:toks[b - 1][2]]


def derive_quote(line, hints, names=()):
    """A short exact excerpt of `line` supporting the hint texts, or None. Never invents text."""
    nl = norm(line)
    if not nl:
        return None
    for h in hints:  # 1. a quoted passage of the entry found in the line
        segs = [next(g for g in m.groups() if g) for m in _QUOTED.finditer(str(h))]
        pieces = [p.strip(" .,;:") for s in sorted(segs, key=len, reverse=True)
                  for p in re.split(r"\.\.\.|…|\[\s*\.\.\.\s*\]|\[…\]", s)]
        for p in sorted(pieces, key=len, reverse=True):
            if len(p) >= 4 and norm(p) in nl:
                words = p.split()
                return " ".join(words[:14]) if len(words) > 14 else p
    toks = [(m.group(0).casefold(), m.start(), m.end()) for m in re.finditer(r"\w+", line)]
    lw = [t[0] for t in toks]
    if not lw:
        return None
    best = None
    for h in hints:  # 2. the longest run of words shared by entry and line
        hw = [w.casefold() for w in re.findall(r"\w+", str(h))]
        if not hw:
            continue
        m = difflib.SequenceMatcher(None, lw, hw, autojunk=False).find_longest_match(0, len(lw), 0, len(hw))
        run = lw[m.a:m.a + m.size]
        content = [w for w in run if w not in _STOP]
        if (m.size >= 4 or (len(content) >= 2 and len("".join(content)) >= 8)) and (best is None or m.size > best[1]):
            best = (m.a, m.size)
    if best:
        return _excerpt(line, toks, best[0], best[0] + best[1])
    stem = lambda w: w[:5] if len(w) > 5 else w
    ls = [stem(w) for w in lw]
    for h in hints:  # 2b. same, comparing word stems (decisione / decise, aspettava / aspettare)
        hs = [stem(w.casefold()) for w in re.findall(r"\w+", str(h))]
        if not hs:
            continue
        m = difflib.SequenceMatcher(None, ls, hs, autojunk=False).find_longest_match(0, len(ls), 0, len(hs))
        content = [lw[k] for k in range(m.a, m.a + m.size) if lw[k] not in _STOP and len(lw[k]) >= 4]
        if len(content) >= 2 and (best is None or m.size > best[1]):
            best = (m.a, m.size)
    if best:
        return _excerpt(line, toks, best[0], best[0] + best[1])
    for nm in sorted((n for n in names if n and len(n) >= 3), key=len, reverse=True):  # 3. a card name in the line
        nw = [w.casefold() for w in re.findall(r"\w+", nm)]
        for k in range(len(lw) - len(nw) + 1):
            if nw and lw[k:k + len(nw)] == nw:
                return _excerpt(line, toks, k, k + len(nw))
    return None


def cmd_migrate(book, args):
    old = Path(args.old_dir).resolve()
    src_cards = old / ("schede" if (old / "schede").exists() else "cards")
    if not src_cards.exists():
        sys.exit(f"{old}: no schede/ folder found")
    if book.dir.exists() and any(book.dir.iterdir()) and not args.force:
        sys.exit(f"{book.dir} already exists: use --force to overwrite")
    if book.dir.exists():
        shutil.rmtree(book.dir)
    book.cards_dir.mkdir(parents=True)
    book.snap_dir.mkdir(parents=True)
    unknown = set()
    old_chs = yaml.safe_load((old / "capitoli.yaml").read_text(encoding="utf-8")) or {}
    scan = scan_chapters(book)
    graph, texts, notes = {}, {}, []
    for n, c in old_chs.items():
        c = rename_keys(c, unknown)
        n = int(n)
        f = book.root / c["file"]
        if not f.exists():
            notes.append(f"chapter {n}: {c['file']} not found — its sources cannot be converted")
            continue
        text = f.read_text(encoding="utf-8")
        cur = scan.get(n, {}).get("version", "?")
        entry = {"title": c.get("title", f.stem), "file": c["file"], "analyzed_version": str(c["analyzed_version"])}
        if c.get("partial"):
            entry["partial"] = True
        if cur != str(c["analyzed_version"]):
            entry["full_reread"] = True
            notes.append(f"chapter {n}: analyzed v{c['analyzed_version']}, file at v{cur} — quotes derived "
                         "from the current text; the chapter will be re-read in full at the next sync")
        graph[n] = entry
        (snapshot_path(book, n)).write_text(text, encoding="utf-8")
        texts[n] = text.split("\n")
    save_graph_chapters(book, graph)

    names = {}
    raw = {}
    for d in sorted(p for p in src_cards.iterdir() if p.is_dir()):
        folder = LEGACY_FOLDERS.get(d.name, d.name)
        if folder not in book.plural.values():
            notes.append(f"folder {d.name}/ has no matching card type in preset '{book.preset}' — skipped")
            continue
        for f in sorted(d.glob("*.yaml")):
            data = rename_keys(yaml.safe_load(f.read_text(encoding="utf-8")) or {}, unknown)
            data = {k: v for k, v in data.items() if v is not None}
            raw[data.get("id", f.stem)] = (folder, data)
            names[data.get("id", f.stem)] = [data.get("name", "")] + list(data.get("aliases", []) or [])

    stats = {"sources": 0, "same": 0, "nearby": 0, "reused": 0, "failed": 0}
    failed, known, pending, todo = [], {}, [], []   # known[(card, ref)] = quotes found on that ref
    for cid, (folder, data) in raw.items():
        for item in source_items(data):
            try:
                refs = parse_refs(item["source"])
            except ValueError as e:
                failed.append((folder, cid, item, str(e), "invalid reference"))
                stats["failed"] += 1
                continue
            own = [h for h in (item.get("text", ""), item.get("note", "")) if h]
            hints = own + ([data["summary"]] if data.get("summary") else [])
            nms = list(names.get(cid, []))
            for k in ("to", "where"):
                nms += names.get(item.get(k), [])
            for x in data.get("involved", []) or []:
                nms += names.get(x, [])
            new_refs, quotes = [], []
            for ch, a, b in refs:
                stats["sources"] += 1
                lines = texts.get(ch)
                if lines is None:
                    failed.append((folder, cid, item, fmt_ref(ch, a, b), "chapter not in capitoli.yaml"))
                    stats["failed"] += 1
                    new_refs.append((ch, a, b))
                    quotes.append(None)
                    continue
                s, e = body_range(lines)
                found = None
                if s <= a <= b <= e:
                    found = derive_quote(" ".join(lines[a - 1:b]), hints, nms)
                    if found and not quote_in(lines, a, b, found):
                        found = None
                if found:
                    stats["same"] += 1
                    new_refs.append((ch, a, b))
                    quotes.append(found)
                    known.setdefault((cid, (ch, a, b)), []).append(found)
                    continue
                for k in sorted(range(max(s, a - 3), min(e, b + 3) + 1), key=lambda k: abs(k - a)):
                    if a <= k <= b:
                        continue
                    qt = derive_quote(lines[k - 1], own) if own else None
                    if qt:
                        found = (k, qt)
                        break
                if found:
                    stats["nearby"] += 1
                    new_refs.append((ch, found[0], found[0]))
                    quotes.append(found[1])
                    notes.append(f"{folder}/{cid}: {fmt_ref(ch, a, b)} re-anchored to "
                                 f"{fmt_ref(ch, found[0], found[0])} (quote found on a nearby line)")
                    continue
                new_refs.append((ch, a, b))
                quotes.append(None)
                pending.append((folder, cid, item, len(quotes) - 1, (ch, a, b)))
            item["source"] = ", ".join(fmt_ref(*x) for x in new_refs)
            item["quote"] = quotes
        data["_path"] = book.cards_dir / folder / f"{cid}.yaml"

    # 4. the same line already gave a quote for this card, or for the card the relation points to
    for folder, cid, item, idx, ref in pending:
        cands = known.get((cid, ref), []) + known.get((item.get("to"), ref), [])
        if cands:
            item["quote"][idx] = cands[0]
            stats["reused"] += 1
            continue
        stats["failed"] += 1
        ch, a, b = ref
        lines = texts.get(ch, [])
        excerpt = " ".join(lines[a - 1:b])[:160] if 0 < a <= len(lines) else "(beyond the end)"
        failed.append((folder, cid, item, fmt_ref(*ref), f"no shared wording with the line: {excerpt}"))
        todo.append({"card": f"{folder}/{cid}", "ref": fmt_ref(*ref), "text": item.get("text") or item.get("note") or "",
                     "to": item.get("to"), "line": " ".join(lines[a - 1:b]), "quote": None})
    for cid, (folder, data) in raw.items():
        for item in source_items(data):
            if isinstance(item.get("quote"), list) and len(item["quote"]) == 1:
                item["quote"] = item["quote"][0]
        write_card(data)

    rep = ["# Graph migration report", "",
           f"From `{old}` · {stats['sources']} sources: {stats['same']} quoted on the same line, "
           f"{stats['nearby']} re-anchored on a nearby line, {stats['reused']} reusing a quote of the same line, "
           f"{stats['failed']} NOT converted.", ""]
    if failed:
        rep += ["## Sources not converted", "",
                "No quote was invented. For each one: read the line, write `quote` (or fix `source`), then "
                "`python3 graph.py build`. The same list, ready to fill, is in `migration-quotes.yaml` "
                "(`python3 graph.py fill-quotes graph/migration-quotes.yaml`).", ""]
        for folder, cid, item, ref, why in failed:
            rep.append(f"- `cards/{folder}/{cid}.yaml` · {ref} · {q(item.get('text') or item.get('note') or '')} — {why}")
        rep.append("")
    if unknown:
        rep += ["## Fields kept with their original name", "", ", ".join(sorted(unknown)), ""]
    if notes:
        rep += ["## Notes", ""] + [f"- {x}" for x in notes] + [""]
    (book.dir / "MIGRATION.md").write_text("\n".join(rep), encoding="utf-8")
    if todo:
        (book.dir / "migration-quotes.yaml").write_text(
            "# Fill `quote` with a short exact excerpt of `line` that supports `text` (or fix `ref`),\n"
            "# then: python3 graph.py fill-quotes graph/migration-quotes.yaml\n"
            + "".join(f"- {flow({k: v for k, v in t.items() if v is not None or k == 'quote'})}\n" for t in todo),
            encoding="utf-8")
    print(f"Migrated {len(raw)} cards, {len(graph)} chapters → {book.dir.relative_to(book.root)}/")
    print(f"Sources: {stats['sources']} · same line {stats['same']} · nearby line {stats['nearby']} · "
          f"same-line quote reused {stats['reused']} · not converted {stats['failed']} (listed in graph/MIGRATION.md)")
    if not failed:
        return cmd_build(book, args)
    return 0


def cmd_fill_quotes(book, args):
    """Write the quotes filled in a migration-quotes.yaml file into the cards."""
    todo = yaml.safe_load(Path(args.file).read_text(encoding="utf-8")) or []
    errs = []
    cards = load_cards(book, errs)
    texts = chapter_texts(book, load_graph_chapters(book))
    done, left, touched = 0, [], {}
    for t in todo:
        if not t.get("quote"):
            left.append(t)
            continue
        cid = t["card"].split("/")[-1]
        card = cards.get(cid)
        old = parse_refs(t["ref"])[0]
        new = parse_refs(t.get("new_ref") or t["ref"])[0]
        hit = None
        for item in source_items(card or {}):
            refs = parse_refs(item["source"])
            qs = quotes_of(item, len(refs))
            for k, (r, qt) in enumerate(zip(refs, qs)):
                if r == old and not qt and (item.get("text") or item.get("note") or "") == t.get("text", "") \
                        and item.get("to") == t.get("to"):
                    hit = (item, k, refs, qs)
                    break
            if hit:
                break
        if not hit:
            print(f"not found: {t['card']} {t['ref']} {q(t.get('text', ''))}")
            left.append(t)
            continue
        lines = texts.get(new[0], [])
        if not quote_in(lines, new[1], new[2], t["quote"]):
            print(f"quote not in {fmt_ref(*new)}: {t['card']} {q(t['quote'])}")
            left.append(t)
            continue
        item, k, refs, qs = hit
        refs[k], qs[k] = new, t["quote"]
        item["source"] = ", ".join(fmt_ref(*x) for x in refs)
        item["quote"] = qs[0] if len(qs) == 1 else qs
        touched[cid] = card
        done += 1
    for c in touched.values():
        write_card(c)
    print(f"{done} quotes written, {len(left)} still missing.")
    return 0 if not left else 1


